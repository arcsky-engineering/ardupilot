#!/usr/bin/env python3
"""
Generate the Xplorer parameter disposition document from firmware source.

    python Tools/xplorer/gen_param_docs.py              # write all outputs
    python Tools/xplorer/gen_param_docs.py --check      # CI: fail on drift
    python Tools/xplorer/gen_param_docs.py --format html

Everything in the output is derived from source. Do not hand-edit the outputs -
edit the inputs and regenerate.

INPUTS (all in-repo)
  hwdef defaults.parm ......... default value + @READONLY  (the disposition truth)
  GCS_Param_Clamps.h .......... enforced Range min/max
  var_info tables ............. AP_PARAM_FLAG_HIDDEN -> user_visible
  Lua applet PARAM_TABLEs ..... script-defined params (no @Param metadata)
  apm.pdef.json ............... display name / description / units / values,
                                generated by Tools/autotest/param_metadata
  param_manifest.txt .......... authoritative row set (see that file's header)
  param_notes.csv ............. HUMAN-AUTHORED notes, the one hand-edited input

OUTPUTS (doc/params/)
  xplorer-params.csv / .xlsx / .html
"""

import argparse
import csv
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))

BOARD = 'CubeOrangePlus-ODID'
VEHICLE = 'ArduCopter'

DEFAULTS_PARM = os.path.join(REPO, 'libraries/AP_HAL_ChibiOS/hwdef', BOARD, 'defaults.parm')
CLAMPS_H = os.path.join(REPO, 'libraries/GCS_MAVLink/GCS_Param_Clamps.h')
PDEF_JSON = os.path.join(REPO, 'apm.pdef.json')
MANIFEST = os.path.join(HERE, 'param_manifest.txt')
NOTES = os.path.join(HERE, 'param_notes.csv')
OVERRIDES = os.path.join(HERE, 'param_meta_overrides.json')
WAIVERS = os.path.join(HERE, 'param_check_waivers.csv')
OUTDIR = os.path.join(REPO, 'doc', 'params')

# Files that may carry AP_PARAM_FLAG_HIDDEN, mapped to the parameter-name prefix
# their var_info table sits under. If a HIDDEN marker turns up in a file that is
# not listed here the run FAILS - that is deliberate, it is the tripwire that
# stops the doc silently going stale when hiding is added somewhere new.
HIDDEN_SOURCES = {
    'ArduCopter/Parameters.cpp': '',
    'libraries/RC_Channel/RC_Channels_VarInfo.h': 'RC',
    'libraries/SRV_Channel/SRV_Channels.cpp': 'SERVO',
}
# HIDDEN markers that are upstream ArduPilot, in groups already hidden wholesale
# or not compiled for this board. Listed so the tripwire stays quiet about them.
HIDDEN_IGNORE = {
    'libraries/AP_ICEngine/AP_ICEngine.cpp',      # ICE_FMT_VER, ICE not enabled
    'libraries/AP_OSD/AP_OSD_Screen.cpp',         # OSD group hidden wholesale
}

# Lua applets whose param:add_table entries should appear in the doc, as
# (tracked path, param prefix). Use the libraries/AP_Scripting/applets copy:
# ArduCopter/scripts/ is gitignored (.gitignore:147), so it is absent on a fresh
# clone. LUA_DEPLOY_MIRROR is the untracked working copy that gets deployed to
# the SD card; if it exists and differs, the run warns rather than silently
# documenting a different script than the one that flies.
LUA_APPLETS = [
    ('libraries/AP_Scripting/applets/copter-fly-figure-8-v2.lua', 'PTRN'),
]
# defaults.parm copies that must stay byte-identical to DEFAULTS_PARM.
# CubeOrangePlus-ODID-DEV needs its own copy because chibios_hwdef.py only looks
# in the board's own directory, not through the include chain; the DEV unlock is
# done at runtime by name, so the files never need to differ.
DEFAULTS_MIRRORS = [
    'libraries/AP_HAL_ChibiOS/hwdef/CubeOrangePlus/defaults.parm',
    'libraries/AP_HAL_ChibiOS/hwdef/CubeOrangePlus-ODID-DEV/defaults.parm',
]
DEV_UNLOCK_H = 'libraries/AP_Param/xplorer_dev_unlock.h'

LUA_DEPLOY_MIRROR = {
    'libraries/AP_Scripting/applets/copter-fly-figure-8-v2.lua':
        'ArduCopter/scripts/copter-fly-figure-8-v2.lua',
}


def warn(msg):
    print('  ! %s' % msg, file=sys.stderr)


