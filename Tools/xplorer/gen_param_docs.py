FIELDS = ['name', 'group', 'default', 'read_only', 'user_visible',
          'clamp_min', 'clamp_max', 'display_name', 'description', 'units',
          'values', 'bitmask', 'doc_range_min', 'doc_range_max',
          'user_level', 'reboot_required', 'notes', 'source']


def flat_kv(v):
    if not isinstance(v, dict):
        return '' if v in (None, '') else str(v)

    def key(k):
        try:
            return (0, float(k))
        except ValueError:
            return (1, k)
    return ', '.join('%s:%s' % (k, v[k]) for k in sorted(v, key=key))


def group_of(name):
    for sep in ('_',):
        if sep in name:
            head = name.split(sep)[0]
            return re.sub(r'\d+$', '', head) or head
    return name


def build(dev=False):
    problems, notices = [], []
    print('Collecting inputs ...')
    ensure_pdef()
    defaults = parse_defaults_parm(DEFAULTS_PARM)
    clamps = parse_clamps(CLAMPS_H)
    hidden_prefixes, hidden_exact = derive_hidden()
    meta = load_pdef()
    names, baseline = load_manifest()
    notes = load_notes()
    waivers = load_waivers()

    lua = {}
    for rel, prefix in LUA_APPLETS:
        lua.update(parse_lua_params(rel, prefix))
        mirror = LUA_DEPLOY_MIRROR.get(rel)
        if mirror:
            mp = os.path.join(REPO, mirror)
            tp = os.path.join(REPO, rel)
            if os.path.exists(mp) and os.path.exists(tp):
                a = open(tp, encoding='utf-8', errors='ignore').read()
                b = open(mp, encoding='utf-8', errors='ignore').read()
                if a != b:
                    problems.append(
                        'Lua applet mirror out of sync: %s differs from the '
                        'tracked %s - the deployed script is not the documented '
                        'one' % (mirror, rel))

    print('  defaults.parm      %d params (%d @READONLY)'
          % (len(defaults), sum(1 for v in defaults.values() if v[1])))
    print('  clamp table        %d' % len(clamps))
    print('  hidden prefixes    %d  + %d individual params'
          % (len(hidden_prefixes), len(hidden_exact)))
    print('  metadata           %d params' % len(meta))
    print('  Lua applet params  %d' % len(lua))
    print('  manifest           %d rows' % len(names))
    print('  human notes        %d' % len(notes))
    print('  check waivers      %d' % len(waivers))

    def is_hidden(n):
        if n in hidden_exact:
            return True
        return any(n.startswith(p) for p in hidden_prefixes)

    unlock = parse_dev_unlock() if dev else []
    if dev:
        print('  DEV unlock         %d prefixes' % len(unlock))

    rows = []
    for n in names:
        m = meta.get(n)
        lu = lua.get(n)
        seeded = n in defaults
        dflt, ro, inline = defaults.get(n, (None, False, ''))
        cl = clamps.get(n)
        if dev:
            if ro and any(n.startswith(pfx) for pfx in unlock):
                ro = False
            cl = None          # the DEV build bypasses the clamp table entirely
        rng = (m.get('Range') or {}) if m else {}
        lrng = lu.get('range') if lu else None

        if lu:
            src = lu['source']
        elif m:
            src = 'apm.pdef.json'
        else:
            src = 'NO METADATA'
            problems.append('no metadata: %s' % n)

        note = notes.get(n, '')
        if inline:
            note = ('defaults.parm: # %s' % inline) + (' | ' + note if note else '')

        rows.append({
            'name': n,
            'group': group_of(n),
            'default': dflt if seeded else (lu['default'] if lu else None),
            'read_only': ro,
            'user_visible': not is_hidden(n),
            'clamp_min': cl[0] if cl else None,
            'clamp_max': cl[1] if cl else None,
            'display_name': (m or {}).get('DisplayName', ''),
            'description': ' '.join(((m or {}).get('Description')
                                     or (lu or {}).get('description', '')).split()),
            'units': (m or {}).get('Units', '') or ('' if not lu else ''),
            'values': flat_kv((m or {}).get('Values')),
            'bitmask': flat_kv((m or {}).get('Bitmask')),
            'doc_range_min': rng.get('low', lrng[0] if lrng else None),
            'doc_range_max': rng.get('high', lrng[1] if lrng else None),
            'user_level': (m or {}).get('User', ''),
            'reboot_required': (m or {}).get('RebootRequired', ''),
            'notes': note,
            'source': src,
        })

    # sanity: a seeded default that falls outside the parameter's own documented
    # range. Either the default is wrong or the range is - both are bugs, and for
    # Lua params the value is silently clamped at read time with no warning.
    for r in rows:
        lo, hi = r['doc_range_min'], r['doc_range_max']
        v = r['default']
        if v is None or lo in (None, '') or hi in (None, ''):
            continue
        try:
            lo, hi, v = float(lo), float(hi), float(v)
        except (TypeError, ValueError):
            continue
        if lo <= v <= hi:
            continue
        msg = ('default out of documented range: %s = %g, range %g..%g%s'
               % (r['name'], v, lo, hi,
                  ' (Lua script clamps this at read time)'
                  if 'Lua applet' in r['source'] else ''))
        if r['name'] in waivers:
            notices.append(msg + '  [waived: %s]' % waivers[r['name']])
        elif v == 0 and lo > 0:
            # Very common upstream idiom: 0 means off/disabled and sits outside
            # the documented "useful" range. Informational, not a defect.
            notices.append(msg + '  [0 = disabled idiom]')
        else:
            problems.append(msg)

    # a clamp-table window that excludes the seeded default would be scrubbed at
    # boot, silently rewriting the shipped default
    for r in rows:
        if r['clamp_min'] is None or r['default'] is None:
            continue
        if not (r['clamp_min'] <= r['default'] <= r['clamp_max']):
            problems.append(
                'seeded default outside its own clamp window (boot scrub will '
                'rewrite it): %s = %g, clamp %g..%g'
                % (r['name'], r['default'], r['clamp_min'], r['clamp_max']))

    # every board's defaults.parm must be byte-identical
    base = open(DEFAULTS_PARM, encoding='utf-8').read()
    for m in DEFAULTS_MIRRORS:
        mp = os.path.join(REPO, m)
        if not os.path.exists(mp):
            problems.append('missing defaults.parm mirror: %s' % m)
        elif open(mp, encoding='utf-8').read() != base:
            problems.append('defaults.parm mirror out of sync: %s differs from '
                            '%s' % (m, os.path.relpath(DEFAULTS_PARM, REPO)))

    # drift checks
    extra = sorted(set(defaults) - set(names))
    if extra:
        problems.append('in defaults.parm but not in the manifest: %s'
                        % ', '.join(extra))
    if baseline:
        added = params_added_since(baseline)
        unlisted = sorted(added - set(names))
        if unlisted:
            problems.append(
                'param(s) added to source since baseline %s but missing from the '
                'manifest: %s' % (baseline, ', '.join(unlisted)))

    meta_info = {
        'generated': datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC'),
        'commit': git('rev-parse', '--short', 'HEAD'),
        'branch': git('rev-parse', '--abbrev-ref', 'HEAD'),
        'describe': git('describe', '--tags', '--always', '--dirty'),
        'board': ('CubeOrangePlus-ODID-DEV (ENGINEERING - params unlocked)'
                  if dev else BOARD),
        'vehicle': VEHICLE,
        'count': len(rows),
        'readonly': sum(1 for r in rows if r['read_only']),
        'hidden': sum(1 for r in rows if not r['user_visible']),
        'clamped': sum(1 for r in rows if r['clamp_min'] is not None),
    }
    return rows, meta_info, problems, notices


def params_added_since(baseline):
    """Param names whose definitions were ADDED to the source after `baseline`."""
    diff = git('diff', '%s..HEAD' % baseline, '--unified=0', '--',
               '*.cpp', '*.h')
    out = set()
    if not diff:
        return out
    # collect added definitions, plus the group prefix is unknown here so we
    # match on suffix later; store bare names.
    for m in re.finditer(r'^\+.*?\b(?:AP_GROUPINFO|AP_GROUPINFO_FLAGS|'
                         r'AP_GROUPINFO_FRAME|AP_GROUPINFO_FLAGS_FRAME|GSCALAR|'
                         r'GSCALAR_HIDDEN|ASCALAR)\s*\(\s*"([A-Za-z0-9_]+)"',
                         diff, re.M):
        out.add(m.group(1))
    return out


