def fmt(v):
    if v is None or v == '':
        return ''
    if isinstance(v, bool):
        return 'True' if v else 'False'
    if isinstance(v, float) and v == int(v) and abs(v) < 1e15:
        return str(int(v))
    return str(v)


def emit_csv(rows, meta_info, path):
    with open(path, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(FIELDS)
        for r in rows:
            w.writerow([fmt(r[k]) for k in FIELDS])
    return path


def emit_xlsx(rows, meta_info, path):
    try:
        import openpyxl
        from openpyxl.styles import Font, PatternFill, Alignment
        from openpyxl.utils import get_column_letter
    except ImportError:
        warn('openpyxl not installed - skipping xlsx (pip install openpyxl)')
        return None
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = 'xplorer-params'
    ws.append([f.replace('_', ' ') for f in FIELDS])
    NUM = {'default', 'clamp_min', 'clamp_max', 'doc_range_min', 'doc_range_max'}
    for r in rows:
        ws.append([r[k] if k in NUM else
                   (r[k] if isinstance(r[k], bool) else fmt(r[k]))
                   for k in FIELDS])
    for c in ws[1]:
        c.font = Font(bold=True)
        c.alignment = Alignment(wrap_text=True, vertical='top')
    ws.freeze_panes = 'B2'
    ws.auto_filter.ref = 'A1:%s%d' % (get_column_letter(len(FIELDS)), ws.max_row)
    widths = {'name': 24, 'group': 10, 'display_name': 30, 'description': 80,
              'notes': 50, 'values': 32, 'bitmask': 32, 'source': 18}
    for i, f in enumerate(FIELDS, start=1):
        ws.column_dimensions[get_column_letter(i)].width = widths.get(f, 12)
    ro = PatternFill('solid', fgColor='FDE9E9')
    for row in ws.iter_rows(min_row=2):
        if row[FIELDS.index('read_only')].value is True:
            row[0].fill = ro

    info = wb.create_sheet('about')
    info.append(['Xplorer parameter disposition'])
    for k in ('generated', 'commit', 'branch', 'describe', 'board', 'vehicle',
              'count', 'readonly', 'hidden', 'clamped'):
        info.append([k, str(meta_info[k])])
    info.append([])
    info.append(['GENERATED FILE - do not hand-edit.'])
    info.append(['Regenerate', 'python Tools/xplorer/gen_param_docs.py'])
