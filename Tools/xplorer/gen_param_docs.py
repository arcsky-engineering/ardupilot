def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--format', default='all',
                    choices=['all', 'csv', 'xlsx', 'html'])
    ap.add_argument('--outdir', default=OUTDIR)
    ap.add_argument('--dev', action='store_true',
                    help='describe the CubeOrangePlus-ODID-DEV build instead: '
                         'applies the xplorer_dev_unlock.h list and drops the '
                         'clamp columns. Writes xplorer-params-DEV.*')
    ap.add_argument('--check', action='store_true',
                    help='regenerate into a temp dir and fail if outputs would '
                         'change or drift is detected (for CI)')
    ap.add_argument('--refresh-metadata', action='store_true',
                    help='force regeneration of apm.pdef.json')
    args = ap.parse_args()

    if args.refresh_metadata and os.path.exists(PDEF_JSON):
        os.remove(PDEF_JSON)

    rows, meta_info, problems, notices = build(dev=args.dev)

    outdir = args.outdir
    if args.check:
        import tempfile
        outdir = tempfile.mkdtemp(prefix='xplorer-params-')
    os.makedirs(outdir, exist_ok=True)
    STEM = 'xplorer-params-DEV' if args.dev else 'xplorer-params'

    written = []
    if args.format in ('all', 'csv'):
        written.append(emit_csv(rows, meta_info, os.path.join(outdir, STEM + '.csv')))
    if args.format in ('all', 'xlsx'):
        p = emit_xlsx(rows, meta_info, os.path.join(outdir, STEM + '.xlsx'))
        if p:
            written.append(p)
    if args.format in ('all', 'html'):
        written.append(emit_html(rows, meta_info, os.path.join(outdir, STEM + '.html')))

    print('\n%d parameters | %d read-only | %d hidden | %d clamped'
          % (meta_info['count'], meta_info['readonly'], meta_info['hidden'],
             meta_info['clamped']))

    if args.check:
        stale = []
        for p in written:
            live = os.path.join(args.outdir, os.path.basename(p))
            if os.path.basename(p).endswith('.xlsx'):
                continue          # xlsx bytes are not reproducible; csv covers it
            if not os.path.exists(live):
                stale.append('%s missing' % os.path.basename(p))
            elif _strip_stamp(open(live, encoding='utf-8').read()) != \
                    _strip_stamp(open(p, encoding='utf-8').read()):
                stale.append('%s out of date' % os.path.basename(p))
        for s in stale:
            problems.append(s)

    if problems:
        print('\nPROBLEMS (%d):' % len(problems), file=sys.stderr)
        for p in problems:
            print('  - %s' % p, file=sys.stderr)
        if args.check:
            print('\nRun: python Tools/xplorer/gen_param_docs.py', file=sys.stderr)
            return 1
    else:
        print('\nNo problems detected.')

    if not args.check:
        for p in written:
            print('  wrote %s' % os.path.relpath(p, REPO))
    return 0


def _strip_stamp(s):
    """Normalise output for --check comparison.

    Drops the generation timestamp so the check does not fire on time alone, and
    normalises line endings so it does not fire merely because a different
    interpreter wrote the file. build_release.sh runs under Cygwin Python (LF)
    while a developer regenerating by hand may use Windows Python (CRLF); either
    should be able to verify the other's output.
    """
    s = s.replace('\r\n', '\n').replace('\r', '\n')
    return re.sub(r'generated \d{4}-\d{2}-\d{2} \d{2}:\d{2} UTC', '', s)


if __name__ == '__main__':
    sys.exit(main())
