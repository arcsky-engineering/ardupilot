def git(*args):
    try:
        return subprocess.check_output(['git', '-C', REPO] + list(args),
                                       text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return ''


def parse_defaults_parm(path):
    """-> {name: (value, readonly, inline_comment)}"""
    out = {}
    for raw in open(path, encoding='utf-8'):
        s = raw.strip()
        if not s or s.startswith('#'):
            continue
        comment = ''
        if '#' in s:
            s, comment = s.split('#', 1)
            comment, s = comment.strip(), s.strip()
        readonly = '@READONLY' in s
        parts = s.replace('@READONLY', '').split()
        if len(parts) < 2:
            warn('unparsed defaults.parm line: %s' % raw.rstrip())
            continue
        try:
            out[parts[0]] = (float(parts[1]), readonly, comment)
        except ValueError:
            warn('unparsed value in defaults.parm: %s' % raw.rstrip())
    return out


def parse_clamps(path):
    src = open(path, encoding='utf-8').read()
    body = src.split('xplorer_param_clamps[]', 1)[-1]
    return {m.group(1): (float(m.group(2)), float(m.group(3)))
            for m in re.finditer(
                r'\{\s*"([A-Z0-9_]+)"\s*,\s*(-?[\d.]+)f\s*,\s*(-?[\d.]+)f\s*\}', body)}


def derive_hidden():
    """Scan the source for AP_PARAM_FLAG_HIDDEN. Returns (prefixes, exact_names).

    Fails loudly if a HIDDEN marker appears in an unregistered file.
    """
    prefixes, exact = [], set()

    found_files = set()
    for root, dirs, files in os.walk(REPO):
        dirs[:] = [d for d in dirs
                   if d not in ('.git', 'build', 'modules', '__pycache__')]
        for fn in files:
            if not fn.endswith(('.cpp', '.h')):
                continue
            p = os.path.join(root, fn)
            rel = os.path.relpath(p, REPO).replace('\\', '/')
            if rel.startswith('libraries/AP_Param/AP_Param'):
                continue          # the macro definitions themselves
            try:
                src = open(p, encoding='utf-8', errors='ignore').read()
            except OSError:
                continue
            if 'AP_PARAM_FLAG_HIDDEN' not in src and '_HIDDEN(' not in src:
                continue
            if re.search(r'^\s*#\s*define\s+\w*_HIDDEN', src, re.M) and \
               'AP_PARAM_FLAG_HIDDEN' not in src:
                continue
            found_files.add(rel)

    unknown = found_files - set(HIDDEN_SOURCES) - HIDDEN_IGNORE
    if unknown:
        raise SystemExit(
            'FAIL: AP_PARAM_FLAG_HIDDEN found in unregistered file(s):\n  ' +
            '\n  '.join(sorted(unknown)) +
            '\n\nAdd each to HIDDEN_SOURCES (with the prefix its var_info sits '
            'under) or HIDDEN_IGNORE in %s, then re-run.' % os.path.basename(__file__))

    for rel, base in HIDDEN_SOURCES.items():
        path = os.path.join(REPO, rel)
        if not os.path.exists(path):
            raise SystemExit('FAIL: HIDDEN_SOURCES lists a missing file: %s' % rel)
        src = open(path, encoding='utf-8', errors='ignore').read()
        src = re.sub(r'^\s*#\s*define.*$', '', src, flags=re.M)

        # whole-group hiding: GOBJECT_HIDDEN(var, "PREFIX", Class)
        for m in re.finditer(r'\b(?:GOBJECT|GOBJECTPTR|GGROUP|GOBJECTN|'
                             r'GOBJECTVARPTR)_HIDDEN\s*\(\s*[^,]+,\s*"([^"]*)"', src):
            prefixes.append(base + m.group(1))
        # nested subgroup: AP_SUBGROUPINFO_HIDDEN(elem, "PREFIX", ...)
        for m in re.finditer(r'\bAP_SUBGROUPINFO_HIDDEN\s*\(\s*[^,]+,\s*"([^"]*)"', src):
            prefixes.append(base + m.group(1))
        # single scalar: GSCALAR_HIDDEN(var, "NAME", def)
        for m in re.finditer(r'\bGSCALAR_HIDDEN\s*\(\s*[^,]+,\s*"([^"]*)"', src):
            exact.add(base + m.group(1))
        # single group param carrying the flag
        for m in re.finditer(r'\bAP_GROUPINFO_FLAGS(?:_FRAME)?\s*\(\s*"([^"]*)"'
                             r'(?:[^;]*?)AP_PARAM_FLAG_HIDDEN', src):
            exact.add(base + m.group(1))

    return sorted(set(prefixes), key=len, reverse=True), exact


def parse_lua_params(rel, prefix):
    """Pull a Lua applet's param:add_table entries and inline comments."""
    path = os.path.join(REPO, rel)
    if not os.path.exists(path):
        warn('Lua applet not found: %s' % rel)
        return {}
    src = open(path, encoding='utf-8', errors='ignore').read()
    m = re.search(r'PARAM_TABLE\s*=\s*\{(.*?)\n\}', src, re.S)
    if not m:
        warn('no PARAM_TABLE found in %s' % rel)
        return {}
    out = {}
    for line in m.group(1).split('\n'):
        e = re.match(r"\s*\{\s*'([A-Z0-9_]+)'\s*,\s*(-?[\d.]+)\s*\}\s*,?\s*(?:--\s*\d*:?\s*(.*))?",
                     line)
        if not e:
            continue
        name = '%s_%s' % (prefix, e.group(1))
        out[name] = {
            'default': float(e.group(2)),
            'description': (e.group(3) or '').strip(),
            'source': 'Lua applet: %s' % rel,
        }
    # Script-side clamps. In the source the name is built with a format string,
    # so the literal text is "%s_NAME", not "<PREFIX>_NAME".
    for e in re.finditer(r"clamp\(\s*(?:math\.floor\(\s*)?param_get\(\s*\(\s*'%s?s?_?([A-Z0-9_]+)'"
                         r".*?,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)", src):
        n = '%s_%s' % (prefix, e.group(1))
        if n in out:
            out[n]['range'] = (float(e.group(2)), float(e.group(3)))
    return out


def ensure_pdef(force=False):
    """Generate apm.pdef.json if absent or older than the newest source file."""
    script = os.path.join(REPO, 'Tools/autotest/param_metadata/param_parse.py')
    if os.path.exists(PDEF_JSON) and not force:
        return
    print('  generating apm.pdef.json (%s) ...' % VEHICLE)
    subprocess.check_call([sys.executable, script, '--vehicle', VEHICLE,
                           '--format', 'json'], cwd=REPO,
                          stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if not os.path.exists(PDEF_JSON):
        raise SystemExit('FAIL: param_parse.py did not produce %s' % PDEF_JSON)


def load_pdef():
    d = json.load(open(PDEF_JSON, encoding='utf-8'))
    meta = {}
    for _, params in d.items():
        if not isinstance(params, dict):
            continue
        for name, m in params.items():
            if isinstance(m, dict):
                meta.setdefault(name, m)
    # Hand-written metadata for params the upstream generator cannot parse.
    if os.path.exists(OVERRIDES):
        ov = json.load(open(OVERRIDES, encoding='utf-8'))
        for name, m in ov.items():
            if name.startswith('_'):
                continue
            if name in meta:
                warn('override for %s is now redundant - upstream parses it, '
                     'consider removing it from %s'
                     % (name, os.path.basename(OVERRIDES)))
            meta[name] = m
    return meta


def load_manifest():
    names, baseline = [], None
    for line in open(MANIFEST, encoding='utf-8'):
        s = line.strip()
        if s.startswith('#'):
            m = re.match(r'#\s*baseline-commit:\s*([0-9a-f]+)', s)
            if m:
                baseline = m.group(1)
            continue
        if s:
            names.append(s)
    return names, baseline


def parse_dev_unlock():
    """Prefixes whose @READONLY is ignored in the DEV build."""
    src = open(os.path.join(REPO, DEV_UNLOCK_H), encoding='utf-8').read()
    try:
        body = src.split('xplorer_dev_unlock[] = {', 1)[1].split('};', 1)[0]
    except IndexError:
        raise SystemExit('FAIL: could not parse the unlock list from %s'
                         % DEV_UNLOCK_H)
    pre = re.findall(r'"([A-Z0-9_]+)"', body)
    if not pre:
        raise SystemExit('FAIL: unlock list in %s is empty' % DEV_UNLOCK_H)
    return pre


def load_waivers():
    """{name: reason} for sanity-check findings that are accepted, not defects."""
    if not os.path.exists(WAIVERS):
        return {}
    return {r['name'].strip(): r.get('reason', '').strip()
            for r in csv.DictReader(open(WAIVERS, encoding='utf-8'))
            if r.get('name', '').strip() and not r['name'].startswith('#')}


def load_notes():
    if not os.path.exists(NOTES):
        return {}
    return {r['name'].strip(): r.get('notes', '').strip()
            for r in csv.DictReader(open(NOTES, encoding='utf-8'))
            if r.get('name', '').strip()}


