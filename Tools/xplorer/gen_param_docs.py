def emit_html(rows, meta_info, path):
    def esc(s):
        return (str(s).replace('&', '&amp;').replace('<', '&lt;')
                .replace('>', '&gt;').replace('"', '&quot;'))

    groups = sorted({r['group'] for r in rows})
    opts = ''.join('<option value="%s">%s</option>' % (esc(g), esc(g))
                   for g in groups)

    out = []
    for r in rows:
        tags = ''
        if r['read_only']:
            tags += '<span class="t ro">RO</span>'
        if not r['user_visible']:
            tags += '<span class="t hd">Hidden</span>'
        if r['clamp_min'] is not None:
            tags += '<span class="t cl">Clamp</span>'

        rng = ''
        if r['clamp_min'] is not None:
            rng = '%s&ndash;%s' % (fmt(r['clamp_min']), fmt(r['clamp_max']))
        elif r['doc_range_min'] not in (None, ''):
            rng = '<span style="color:var(--mut)">%s&ndash;%s</span>' % (
                fmt(r['doc_range_min']), fmt(r['doc_range_max']))
        if r['units']:
            rng += ' <span style="color:var(--mut)">%s</span>' % esc(r['units'])

        body = ''
        if r['display_name']:
            body += '<div class="dn">%s</div>' % esc(r['display_name'])
        if r['description']:
            body += '<div class="ds">%s</div>' % esc(r['description'])
        enum = r['values'] or r['bitmask']
        if enum:
            label = 'Values' if r['values'] else 'Bitmask'
            body += '<div class="en">%s: %s</div>' % (label, esc(enum))
        if r['notes']:
            body += '<div class="nt">%s</div>' % esc(r['notes'])

        srch = ' '.join([r['name'], r['display_name'], r['description'],
                         r['notes'], enum]).lower()
        out.append(
            '<tr class="p" data-s="%s" data-g="%s" data-ro="%s" data-hd="%s"'
            ' data-cl="%s" data-nt="%s">'
            '<td class="nm"><a id="%s" href="#%s">%s</a></td>'
            '<td class="dv">%s</td><td class="tags">%s</td>'
            '<td class="co dv">%s</td><td>%s</td></tr>'
            % (esc(srch), esc(r['group']), '1' if r['read_only'] else '0',
               '0' if r['user_visible'] else '1',
               '1' if r['clamp_min'] is not None else '0',
               '1' if r['notes'] else '0',
               esc(r['name']), esc(r['name']), esc(r['name']),
               fmt(r['default']) or '<span style="color:var(--mut)">&mdash;</span>',
               tags or '<span style="color:var(--mut)">&mdash;</span>',
               rng or '&mdash;', body))

    html = HTML_TMPL
    for k, v in [('__BOARD__', meta_info['board']),
                 ('__VEHICLE__', meta_info['vehicle']),
                 ('__GENERATED__', meta_info['generated']),
                 ('__COMMIT__', meta_info['commit']),
                 ('__BRANCH__', meta_info['branch']),
                 ('__DESCRIBE__', esc(meta_info['describe'])),
                 ('__COUNT__', str(meta_info['count'])),
                 ('__READONLY__', str(meta_info['readonly'])),
                 ('__HIDDEN__', str(meta_info['hidden'])),
                 ('__CLAMPED__', str(meta_info['clamped'])),
                 ('__GROUPS__', opts),
                 ('__ROWS__', '\n'.join(out))]:
        html = html.replace(k, v)
    # newline='\n' so the bytes are identical no matter which interpreter writes
    # them. Without it, Windows Python translates \n -> \r\n while Cygwin Python
    # does not, so a file written by one looks "out of date" to the other and
    # --check fails forever. build_release.sh runs under Cygwin; a developer
    # regenerating from a Windows shell does not.
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html)
    return path


